import { forwardRef } from 'react';
import { cn } from '../../utils/cn';

export const Card = forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        'rounded-lg border border-line bg-bg text-ink',
        'shadow-xs',
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = 'Card';

