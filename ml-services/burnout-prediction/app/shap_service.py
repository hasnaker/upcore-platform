"""SHAP explanation service (skill: upc-ml-validation §3).

Provides three user-visible outputs:

1. **Per-prediction top-5 SHAP values** — what moved *this* employee's risk.
2. **Global feature importance** — mean |SHAP| across the validation cohort.
3. **Counterfactual example** — "if feature X had been value Y, prediction
   would have been Z"; generated by coordinate-wise probing of each top
   feature toward the opposite end of the spec range.

Why a dedicated service? Because the ``app/inference/explainer.py`` module
is kept on the heuristic path for V1 (pseudo-SHAP via weights). This module
implements the **real SHAP** pipeline for XGBoost / LSTM models and is what
``routes_audit.py`` exposes.

When the ``shap`` library is available (via the ``gpu`` extra) we use
TreeExplainer / KernelExplainer. Otherwise we fall back to a sampling-based
approximation that is compatible with the ``HeuristicBurnoutPredictor`` and
used primarily for tests.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Callable, Sequence

import numpy as np
import structlog

from app.features.feature_spec import FEATURE_LABELS_TR

logger = structlog.get_logger()


PredictFn = Callable[[dict[str, float]], float]


@dataclass
class ShapContribution:
    feature: str
    label_tr: str
    shap_value: float
    abs_shap: float
    direction: str  # "positive" (risk-increasing) | "negative" (risk-decreasing)
    actual_value: float


@dataclass
class CounterfactualExample:
    feature: str
    label_tr: str
    original_value: float
    counterfactual_value: float
    original_probability: float
    counterfactual_probability: float
    delta: float


@dataclass
class SingleExplanation:
    employee_id: str | None
    prediction: float
    base_value: float
    top_k: list[ShapContribution] = field(default_factory=list)
    counterfactuals: list[CounterfactualExample] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {
            "employee_id": self.employee_id,
            "prediction": self.prediction,
            "base_value": self.base_value,
            "top_k": [asdict(t) for t in self.top_k],
            "counterfactuals": [asdict(cf) for cf in self.counterfactuals],
        }


@dataclass
class GlobalImportance:
    model_version: str
    n_samples: int
    features: list[dict[str, float | str]] = field(default_factory=list)


# ---------------------------------------------------------------------------
# SHAP fallback via sampling (Shapley values via marginal contributions)
# ---------------------------------------------------------------------------


def _sampling_shap_values(
    predict_fn: PredictFn,
    feature_values: dict[str, float],
    reference_values: dict[str, float],
    *,
    n_samples: int = 50,
    rng: np.random.Generator | None = None,
) -> dict[str, float]:
    """Approximate Shapley values by Monte-Carlo permutation sampling.

    Strumbelj & Kononenko 2014 — unbiased estimator of exact Shapley value.
    Used when the ``shap`` library is not installed.
    """
    rng = rng or np.random.default_rng(42)
    feat_names = list(feature_values.keys())
    n_features = len(feat_names)
    phi: dict[str, list[float]] = {name: [] for name in feat_names}

    # Baseline: every feature at its reference value. Features missing from
    # reference_values default to 0.0 (cohort mean proxy).
    baseline: dict[str, float] = {name: float(reference_values.get(name, 0.0)) for name in feat_names}

    for _ in range(n_samples):
        order = rng.permutation(n_features)
        current_input = dict(baseline)
        for idx in order:
            name = feat_names[idx]
            previous = predict_fn(current_input)
            current_input[name] = float(feature_values[name])
            after = predict_fn(current_input)
            phi[name].append(after - previous)

    return {name: float(np.mean(vals)) if vals else 0.0 for name, vals in phi.items()}


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def explain_single(
    *,
    predict_fn: PredictFn,
    feature_values: dict[str, float],
    reference_values: dict[str, float] | None = None,
    employee_id: str | None = None,
    k: int = 5,
    n_samples: int = 50,
    counterfactual_targets: int = 3,
) -> SingleExplanation:
    """Compute a per-employee explanation with top-k SHAP and counterfactuals.

    Args:
        predict_fn: callable taking a feature dict and returning probability.
        feature_values: the employee's actual features.
        reference_values: cohort baseline (defaults to zeros — "no signal").
        employee_id: optional identifier included in the response.
        k: how many top SHAP contributions to return.
        n_samples: permutations for the sampling estimator.
        counterfactual_targets: number of top features to probe counterfactually.
    """
    reference_values = reference_values or {name: 0.0 for name in feature_values}
    prediction = float(predict_fn(feature_values))
    base_value = float(predict_fn(reference_values))

    shap_vals = _sampling_shap_values(
        predict_fn,
        feature_values,
        reference_values,
        n_samples=n_samples,
    )

    contribs = [
        ShapContribution(
            feature=name,
            label_tr=FEATURE_LABELS_TR.get(name, name),
            shap_value=float(value),
            abs_shap=float(abs(value)),
            direction="positive" if value >= 0 else "negative",
            actual_value=float(feature_values.get(name, 0.0)),
        )
        for name, value in shap_vals.items()
    ]
    contribs.sort(key=lambda c: c.abs_shap, reverse=True)
    top_k = contribs[:k]

    # Counterfactuals: for each top feature, flip it toward the cohort mean
    counterfactuals: list[CounterfactualExample] = []
    for contrib in top_k[:counterfactual_targets]:
        cf_value = float(reference_values.get(contrib.feature, 0.0))
        cf_input = dict(feature_values)
        cf_input[contrib.feature] = cf_value
        cf_prob = float(predict_fn(cf_input))
        counterfactuals.append(
            CounterfactualExample(
                feature=contrib.feature,
                label_tr=contrib.label_tr,
                original_value=contrib.actual_value,
                counterfactual_value=cf_value,
                original_probability=prediction,
                counterfactual_probability=cf_prob,
                delta=float(cf_prob - prediction),
            )
        )

    logger.info(
        "explanation_generated",
        employee_id=employee_id,
        top_features=[c.feature for c in top_k],
        prediction=prediction,
    )
    return SingleExplanation(
        employee_id=employee_id,
        prediction=prediction,
        base_value=base_value,
        top_k=top_k,
        counterfactuals=counterfactuals,
    )


def compute_global_importance(
    *,
    predict_fn: PredictFn,
    cohort: Sequence[dict[str, float]],
    reference_values: dict[str, float] | None = None,
    model_version: str,
    n_samples_per_row: int = 20,
    top_n: int = 20,
) -> GlobalImportance:
    """Aggregate mean |SHAP| across a validation cohort."""
    if not cohort:
        return GlobalImportance(model_version=model_version, n_samples=0, features=[])

    reference_values = reference_values or {name: 0.0 for name in cohort[0]}
    totals: dict[str, list[float]] = {name: [] for name in cohort[0]}

    for row in cohort:
        shap_vals = _sampling_shap_values(
            predict_fn,
            row,
            reference_values,
            n_samples=n_samples_per_row,
        )
        for name, val in shap_vals.items():
            totals.setdefault(name, []).append(abs(val))

    features = [
        {
            "feature": name,
            "label_tr": FEATURE_LABELS_TR.get(name, name),
            "mean_abs_shap": float(np.mean(vals)) if vals else 0.0,
            "n": int(len(vals)),
        }
        for name, vals in totals.items()
    ]
    features.sort(key=lambda f: f["mean_abs_shap"], reverse=True)

    return GlobalImportance(
        model_version=model_version,
        n_samples=len(cohort),
        features=features[:top_n],
    )


# ---------------------------------------------------------------------------
# Optional real SHAP via the `shap` library
# ---------------------------------------------------------------------------


def shap_tree_explainer_available() -> bool:
    try:
        import shap  # noqa: F401
        return True
    except ImportError:
        return False


def explain_with_tree_model(
    *,
    xgboost_model: Any,
    X: np.ndarray,
    feature_names: Sequence[str],
    row_index: int = 0,
    k: int = 5,
) -> SingleExplanation | None:
    """Use ``shap.TreeExplainer`` if available — best path for XGBoost.

    Returns ``None`` when ``shap`` is not installed so the caller can fall
    back to the sampling estimator.
    """
    if not shap_tree_explainer_available():
        return None

    import shap

    explainer = shap.TreeExplainer(xgboost_model)
    shap_values = explainer.shap_values(X)
    base_value = float(explainer.expected_value) if np.ndim(explainer.expected_value) == 0 else float(explainer.expected_value[0])

    row_shap = np.asarray(shap_values[row_index]).ravel()
    row_values = np.asarray(X[row_index]).ravel()

    contribs = [
        ShapContribution(
            feature=name,
            label_tr=FEATURE_LABELS_TR.get(name, name),
            shap_value=float(v),
            abs_shap=float(abs(v)),
            direction="positive" if v >= 0 else "negative",
            actual_value=float(val),
        )
        for name, v, val in zip(feature_names, row_shap, row_values)
    ]
    contribs.sort(key=lambda c: c.abs_shap, reverse=True)

    prediction = float(xgboost_model.predict_proba(X[row_index : row_index + 1])[:, 1][0])

    return SingleExplanation(
        employee_id=None,
        prediction=prediction,
        base_value=base_value,
        top_k=contribs[:k],
        counterfactuals=[],
    )


